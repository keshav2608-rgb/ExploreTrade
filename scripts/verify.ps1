# Regenerates VERIFICATION.md: every claim in README.md that can be checked
# by running something is checked here, and the unedited output is kept.
#
#   scripts\verify.ps1            # tests, build, API smoke test, provider check, feed
#   scripts\verify.ps1 -SkipFeed  # without the Rust feed (no Rust toolchain needed)
#
# Needs: Node 20+, a filled-in .env (copy .env.example), and for the feed
# steps a Rust toolchain. Uses port 3000 for the app and 8790/8791 for the feed.
param([switch] $SkipFeed, [int] $LiveSeconds = 25)
$ErrorActionPreference = "Continue"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$out = Join-Path $root "VERIFICATION.md"
$failed = @()
$envFile = Get-Content .env | Where-Object { $_ -match "=" -and -not $_.StartsWith("#") }
$cronSecret = ($envFile | Where-Object { $_ -like "CRON_SECRET=*" } | Select-Object -First 1) -replace '^CRON_SECRET=', '' -replace '"', ''

function Section($title, $cmd) { Add-Content $out "`n## $title`n`nCommand:`n`n``````"; Add-Content $out $cmd; Add-Content $out "``````"; Add-Content $out "`nOutput:`n`n``````" }
function EndSection { Add-Content $out "``````" }
function Run($title, $cmd, [scriptblock] $block) {
    Write-Host ">> $title" -ForegroundColor Cyan
    Section $title $cmd
    $global:LASTEXITCODE = 0
    try {
        $text = (& $block 2>&1 | Out-String) -replace "`e\[[0-9;]*m", ""
        Add-Content $out $text.TrimEnd()
        if ($LASTEXITCODE -ne 0) { $script:failed += $title; Add-Content $out "`n(exit code $LASTEXITCODE)" }
    } catch { $script:failed += $title; Add-Content $out "ERROR: $_" }
    EndSection
}
function Stop-Port($port) {
    $c = Get-NetTCPConnection -LocalPort $port -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($c) { Stop-Process -Id $c.OwningProcess -Force -ErrorAction SilentlyContinue; Start-Sleep 1 }
}
function Wait-Http($url, $seconds = 40) {
    for ($i = 0; $i -lt $seconds; $i++) { try { if ((Invoke-WebRequest -UseBasicParsing $url -TimeoutSec 2).StatusCode -eq 200) { return $true } } catch {}; Start-Sleep 1 }
    return $false
}

foreach ($p in 3000, 8790, 8791) {
    if (Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue) { Write-Host "Port $p is in use. Stop whatever is listening there and re-run." -ForegroundColor Red; exit 1 }
}

$cpu = Get-CimInstance Win32_Processor | Select-Object -First 1
$os = Get-CimInstance Win32_OperatingSystem
@"
# Verification record

Generated by ``scripts\verify.ps1`` on $(Get-Date -Format "yyyy-MM-dd HH:mm:ss K").
Each section is the unedited output of the command shown above it.

| | |
|---|---|
| CPU | $($cpu.Name.Trim()), $($cpu.NumberOfCores) cores |
| OS | $($os.Caption) $($os.Version) |
| Node | $(node --version) / npm $(npm --version) |
| Rust | $(if (Get-Command cargo -ErrorAction SilentlyContinue) { cargo --version } else { "not installed (feed steps skipped)" }) |
| Provider in .env | $(($envFile | Where-Object { $_ -like "MARKET_DATA_PROVIDER=*" }) -replace '^MARKET_DATA_PROVIDER=', '') |
"@ | Set-Content $out -Encoding utf8

Run "1. Unit and integration tests" "npx vitest run" { npx vitest run 2>&1 | Select-String -Pattern "tests/|Test Files|Tests |FAIL|Error" | ForEach-Object { $_.Line } }
Run "2. Type-check and production build" "npx tsc --noEmit; npx next build" { npx tsc --noEmit; if ($LASTEXITCODE -eq 0) { "tsc: no type errors" }; npx next build 2>&1 | Select-String -Pattern "Compiled|error|Route \(app\)|^\S\s+/" | ForEach-Object { $_.Line } }
Run "3. Database setup (migrations + seed)" "npx prisma migrate deploy; npx tsx prisma/seed.ts" { npx prisma migrate deploy 2>&1 | Select-String -Pattern "migration|No pending|applied" | ForEach-Object { $_.Line }; npx tsx prisma/seed.ts }

$server = Start-Process -FilePath "npx.cmd" -ArgumentList "next start -p 3000" -PassThru -WindowStyle Hidden -RedirectStandardOutput "data-server.log" -RedirectStandardError "data-server.err.log"
if (-not (Wait-Http "http://localhost:3000/api/health")) { Write-Host "app did not start; see data-server.err.log" -ForegroundColor Red; $failed += "app start" }

Run "4. End-to-end API smoke test (SRS section 15 acceptance criteria)" "npx next start -p 3000`nnode scripts/smoke.mjs http://localhost:3000" { node scripts/smoke.mjs http://localhost:3000 }
Run "5. Market-data provider check: demo" "npx tsx scripts/check-provider.ts demo" { npx tsx scripts/check-provider.ts demo }
Run "6. Market-data provider check: yahoo (real, delayed)" "npx tsx scripts/check-provider.ts yahoo" { npx tsx scripts/check-provider.ts yahoo }
Run "7. Scheduled check with a controlled test quote" "curl -X POST -H 'Authorization: Bearer `$CRON_SECRET' -d '{}' http://localhost:3000/api/cron/check-alerts" {
    (Invoke-WebRequest -UseBasicParsing -Method Post -Uri "http://localhost:3000/api/cron/check-alerts" -Headers @{ Authorization = "Bearer $cronSecret" } -ContentType "application/json" -Body "{}").Content
}

if (-not $SkipFeed -and (Get-Command cargo -ErrorAction SilentlyContinue)) {
    Push-Location services\pulsefeed
    Run "8. PulseFeed: build and unit tests (SIMD vs scalar, token verification, SoA totals)" "cd services/pulsefeed; cargo build --release; cargo test --release" {
        cargo build --release 2>&1 | Select-String -Pattern "Finished|error" | ForEach-Object { $_.Line }
        cargo test --release 2>&1 | Select-String -Pattern "^test |test result" | ForEach-Object { $_.Line }
    }
    Pop-Location
    $env:CRON_SECRET = $cronSecret
    Run "9. PulseFeed: one real poll (Yahoo, delayed) pushed into the app" "services/pulsefeed/target/release/pulsefeed --once --provider yahoo" {
        & services\pulsefeed\target\release\pulsefeed.exe --once --provider yahoo 2>&1
    }
    $feed = Start-Process -FilePath "services\pulsefeed\target\release\pulsefeed.exe" -ArgumentList "--provider demo --poll-seconds 5" -PassThru -WindowStyle Hidden -RedirectStandardError "data-feed.log"
    Start-Sleep 3
    Run "10. PulseFeed: WebSocket live totals reach a logged-in client" "services/pulsefeed/target/release/pulsefeed --provider demo --poll-seconds 5`nnode scripts/live-check.mjs http://localhost:3000 $LiveSeconds" {
        node scripts/live-check.mjs http://localhost:3000 $LiveSeconds
        "--- feed /health ---"
        (Invoke-WebRequest -UseBasicParsing "http://127.0.0.1:8791/health").Content
    }
    Stop-Process -Id $feed.Id -Force -ErrorAction SilentlyContinue
    Remove-Item Env:CRON_SECRET
}

Stop-Process -Id $server.Id -Force -ErrorAction SilentlyContinue
Stop-Port 3000

Add-Content $out "`n## Result`n"
if ($failed.Count -eq 0) { Add-Content $out "All steps completed."; Write-Host "All steps completed. See VERIFICATION.md" -ForegroundColor Green }
else { Add-Content $out ("Steps with errors: " + ($failed -join "; ")); Write-Host ("Steps with errors: " + ($failed -join "; ")) -ForegroundColor Yellow; exit 1 }
