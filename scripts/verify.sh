#!/usr/bin/env bash
# Regenerates VERIFICATION.md on Linux/macOS: every runnable claim in the
# README is run here and its unedited output kept.
#
#   ./scripts/verify.sh              # tests, build, API smoke, provider check, feed
#   ./scripts/verify.sh --skip-feed  # without the Rust feed
set -uo pipefail
cd "$(dirname "$0")/.."
SKIP_FEED=0; LIVESEC=25
for a in "$@"; do case "$a" in --skip-feed) SKIP_FEED=1;; esac; done
OUT=VERIFICATION.md; FAILED=()
CRON_SECRET=$(grep -E '^CRON_SECRET=' .env | head -1 | cut -d= -f2- | tr -d '"')

section() { printf '\n## %s\n\nCommand:\n\n```\n%s\n```\n\nOutput:\n\n```\n' "$1" "$2" >> "$OUT"; }
run() { echo ">> $1"; section "$1" "$2"; if ! "$3" 2>&1 | sed -r 's/\x1b\[[0-9;]*m//g' >> "$OUT"; then FAILED+=("$1"); echo "(step reported an error)" >> "$OUT"; fi; printf '```\n' >> "$OUT"; }
wait_http() { for _ in $(seq 1 40); do curl -sf "$1" >/dev/null && return 0; sleep 1; done; return 1; }

for p in 3000 8790 8791; do if (exec 3<>/dev/tcp/127.0.0.1/$p) 2>/dev/null; then exec 3>&-; echo "Port $p is in use; stop it and re-run." >&2; exit 1; fi; done

{
  echo "# Verification record"; echo
  echo "Generated by \`scripts/verify.sh\` on $(date -u '+%Y-%m-%d %H:%M:%S UTC'). Each section is the unedited output of the command shown."
  echo; echo "| | |"; echo "|---|---|"
  echo "| OS | $(uname -srm) |"; echo "| Node | $(node --version) / npm $(npm --version) |"
  echo "| Rust | $(cargo --version 2>/dev/null || echo 'not installed (feed steps skipped)') |"
  echo "| Provider in .env | $(grep -E '^MARKET_DATA_PROVIDER=' .env | cut -d= -f2-) |"
} > "$OUT"

t1() { npx vitest run 2>&1 | grep -E "tests/|Test Files|Tests |FAIL|Error"; }
run "1. Unit and integration tests" "npx vitest run" t1
t2() { npx tsc --noEmit && echo "tsc: no type errors"; npx next build 2>&1 | grep -E "Compiled|error|Route \(app\)|^. +/"; }
run "2. Type-check and production build" "npx tsc --noEmit; npx next build" t2
t3() { npx prisma migrate deploy 2>&1 | grep -Ei "migration|no pending|applied"; npx tsx prisma/seed.ts; }
run "3. Database setup (migrations + seed)" "npx prisma migrate deploy; npx tsx prisma/seed.ts" t3

npx next start -p 3000 > data-server.log 2>&1 &
SERVER=$!
wait_http http://localhost:3000/api/health || { echo "app did not start" >&2; FAILED+=("app start"); }
t4() { node scripts/smoke.mjs http://localhost:3000; }
run "4. End-to-end API smoke test (SRS section 15 acceptance criteria)" "npx next start -p 3000
node scripts/smoke.mjs http://localhost:3000" t4
t5() { npx tsx scripts/check-provider.ts demo; }
run "5. Market-data provider check: demo" "npx tsx scripts/check-provider.ts demo" t5
t6() { npx tsx scripts/check-provider.ts yahoo; }
run "6. Market-data provider check: yahoo (real, delayed)" "npx tsx scripts/check-provider.ts yahoo" t6
t7() { curl -s -X POST -H "Authorization: Bearer $CRON_SECRET" -H "content-type: application/json" -d '{}' http://localhost:3000/api/cron/check-alerts; echo; }
run "7. Scheduled check with a controlled test quote" "curl -X POST -H 'Authorization: Bearer \$CRON_SECRET' -d '{}' http://localhost:3000/api/cron/check-alerts" t7

if [ "$SKIP_FEED" = 0 ] && command -v cargo >/dev/null; then
  t8() { (cd services/pulsefeed && cargo build --release 2>&1 | grep -E "Finished|error" && cargo test --release 2>&1 | grep -E "^test |test result"); }
  run "8. PulseFeed: build and unit tests (SIMD vs scalar, token verification, SoA totals)" "cd services/pulsefeed; cargo build --release; cargo test --release" t8
  export CRON_SECRET
  t9() { services/pulsefeed/target/release/pulsefeed --once --provider yahoo; }
  run "9. PulseFeed: one real poll (Yahoo, delayed) pushed into the app" "services/pulsefeed/target/release/pulsefeed --once --provider yahoo" t9
  services/pulsefeed/target/release/pulsefeed --provider demo --poll-seconds 5 2> data-feed.log &
  FEED=$!; sleep 3
  t10() { node scripts/live-check.mjs http://localhost:3000 "$LIVESEC"; echo "--- feed /health ---"; curl -s http://127.0.0.1:8791/health; echo; }
  run "10. PulseFeed: WebSocket live totals reach a logged-in client" "services/pulsefeed/target/release/pulsefeed --provider demo --poll-seconds 5
node scripts/live-check.mjs http://localhost:3000 $LIVESEC" t10
  kill "$FEED" 2>/dev/null
fi

kill "$SERVER" 2>/dev/null
printf '\n## Result\n\n' >> "$OUT"
if [ ${#FAILED[@]} -eq 0 ]; then echo "All steps completed." | tee -a "$OUT"; else echo "Steps with errors: ${FAILED[*]}" | tee -a "$OUT"; exit 1; fi
